# Direct synchronous joint (delta, theta) P objective fixtures.  This is the
# f_scalar implementation used inside compute_local_for_theta_delta, evaluated
# at physical parameter vectors [delta, alpha, range].
points = [[1.7, 1.2, .8], [1.75, 1.2, .8], [1.65, 1.2, .8],
          [1.7, 1.25, .8], [1.7, 1.15, .8], [1.7, 1.2, .85], [1.7, 1.2, .75]]
def delta_theta_value(local_data, point):
    worker = LocalComputation(local_data, Matern_1_5_kernel, knots)
    worker.type_LR = "P"
    var = torch.tensor(point, dtype=torch.float64, requires_grad=True)
    dl, th = var[0], var[1:]
    B, _ = worker.local_B(th)
    err = worker.local_errorv(para.gamma)
    r = err + B @ para.mu
    inv = worker.local_inv(th, dl)
    BsigB = B @ para.sigma @ B.T
    value = (-worker.local_data.shape[0] * torch.log(dl) - torch.logdet(inv)
             + dl * (r.T @ inv @ r + torch.trace(inv @ BsigB))).squeeze()
    grad = torch.autograd.grad(value, var, create_graph=True)[0]
    hess = torch.autograd.functional.hessian(lambda v: (-worker.local_data.shape[0] * torch.log(v[0]) - torch.logdet(worker.local_inv(v[1:], v[0])) + v[0] * ((worker.local_errorv(para.gamma) + worker.local_B(v[1:])[0] @ para.mu).T @ worker.local_inv(v[1:], v[0]) @ (worker.local_errorv(para.gamma) + worker.local_B(v[1:])[0] @ para.mu) + torch.trace(worker.local_inv(v[1:], v[0]) @ (worker.local_B(v[1:])[0] @ para.sigma @ worker.local_B(v[1:])[0].T)))).squeeze(), var)
    return value.detach().reshape(1,1), grad.detach().reshape(-1,1), hess.detach()
for i, point in enumerate(points):
    value, grad, hess = delta_theta_value(data[0], point)
    write(f"DELTA_THETA_POINT{i}_PARAM", torch.tensor(point).reshape(-1,1))
    write(f"DELTA_THETA_POINT{i}_OBJECTIVE", value)
    write(f"DELTA_THETA_POINT{i}_GRAD", grad)
    write(f"DELTA_THETA_POINT{i}_HESSIAN", hess)

# Direct autograd fixtures for second derivatives of K, C_jstar, and B=C K^-1.
for i, point in enumerate(points):
    v = torch.tensor(point[1:], dtype=torch.float64, requires_grad=True)
    for tag, fun in [("K", lambda th: Matern_1_5_kernel(knots, knots, th)),
                     ("CROSS", lambda th: Matern_1_5_kernel(data[0][:,:2], knots, th)),
                     ("B", lambda th: Matern_1_5_kernel(data[0][:,:2], knots, th) @ torch.linalg.inv(Matern_1_5_kernel(knots, knots, th)))]:
        value = fun(v)
        for name, a, b in [("AA",0,0),("AR",0,1),("RA",1,0),("RR",1,1)]:
            hmat = torch.zeros_like(value)
            for row in range(value.shape[0]):
                for col in range(value.shape[1]):
                    h = torch.autograd.functional.hessian(lambda th: fun(th)[row,col], v)
                    hmat[row,col] = h[a,b]
            write(f"DELTA_THETA_POINT{i}_{tag}_HESS_{name}", hmat)

# Direct autograd fixtures for Cjj and A=Cjj-B K B.T.  The closures retain the
# exact reference B/K construction, so every element is differentiated through
# the same computation graph used by the synchronous P-residual path.
fixture_cjj_symmetry = 0.0
fixture_a_symmetry = 0.0
for i, point in enumerate(points):
    theta = torch.tensor(point[1:], dtype=torch.float64, requires_grad=True)
    worker = LocalComputation(data[0], Matern_1_5_kernel, knots)
    worker.type_LR = "P"

    def cjj_graph(th):
        return Matern_1_5_kernel(data[0][:, :2], data[0][:, :2], th)

    def a_graph(th):
        B, K = worker.local_B(th)
        return cjj_graph(th) - B @ K @ B.T

    point_derivatives = {}
    for tag, graph in [("CJJ", cjj_graph), ("A", a_graph)]:
        value = graph(theta)
        if value.shape != (3, 3):
            raise RuntimeError(f"POINT{i}_{tag} has unexpected shape {value.shape}")
        for name, row_index, col_index in [("AA", 0, 0), ("AR", 0, 1),
                                           ("RA", 1, 0), ("RR", 1, 1)]:
            hmat = torch.zeros_like(value)
            for row in range(value.shape[0]):
                for col in range(value.shape[1]):
                    hessian_entry = torch.autograd.functional.hessian(
                        lambda th: graph(th)[row, col], theta)
                    hmat[row, col] = hessian_entry[row_index, col_index]
            if not torch.isfinite(hmat).all():
                raise RuntimeError(f"POINT{i}_{tag}_HESS_{name} contains non-finite values")
            write(f"DELTA_THETA_POINT{i}_{tag}_HESS_{name}", hmat)
            point_derivatives[f"{tag}_{name}"] = hmat
    fixture_cjj_symmetry = max(
        fixture_cjj_symmetry,
        torch.max(torch.abs(point_derivatives["CJJ_AR"] - point_derivatives["CJJ_RA"])).item())
    fixture_a_symmetry = max(
        fixture_a_symmetry,
        torch.max(torch.abs(point_derivatives["A_AR"] - point_derivatives["A_RA"])).item())

fixture_ok = fixture_cjj_symmetry <= 1e-10 and fixture_a_symmetry <= 1e-10
print(f"FIXTURE_CJJ_HESS_SYMMETRY_MAX_ABS_ERROR={fixture_cjj_symmetry}")
print(f"FIXTURE_A_HESS_SYMMETRY_MAX_ABS_ERROR={fixture_a_symmetry}")
print(f"A_HESS_FIXTURE_EXPORT={'PASS' if fixture_ok else 'FAIL'}")
if not fixture_ok:
    raise RuntimeError("A Hessian fixture symmetry check failed")

# Direct graph derivatives for M=delta*(Cjj-B K B.T)+I.  Each output matrix is
# a Jacobian slice with respect to the physical vector [delta, alpha, range].
for i, point in enumerate(points):
    var = torch.tensor(point, dtype=torch.float64, requires_grad=True)
    worker = LocalComputation(data[0], Matern_1_5_kernel, knots)
    worker.type_LR = "P"
    def m_graph(v):
        B, K = worker.local_B(v[1:])
        Cjj = Matern_1_5_kernel(data[0][:, :2], data[0][:, :2], v[1:])
        return v[0] * (Cjj - B @ K @ B.T) + torch.eye(Cjj.shape[0], dtype=torch.float64)
    jac = torch.autograd.functional.jacobian(m_graph, var)
    for name, component in [("DELTA", 0), ("ALPHA", 1), ("RANGE", 2)]:
        write(f"DELTA_THETA_POINT{i}_M_GRAD_{name}", jac[:, :, component])
    for name, row_index, col_index in [("DD",0,0),("DA",0,1),("DR",0,2),
                                       ("AD",1,0),("AA",1,1),("AR",1,2),
                                       ("RD",2,0),("RA",2,1),("RR",2,2)]:
        hmat = torch.zeros((3, 3), dtype=torch.float64)
        for row in range(3):
            for col in range(3):
                hmat[row, col] = torch.autograd.functional.hessian(
                    lambda v: m_graph(v)[row, col], var)[row_index, col_index]
        write(f"DELTA_THETA_POINT{i}_M_HESS_{name}", hmat)

