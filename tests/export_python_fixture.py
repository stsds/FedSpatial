def export_n_checkpoints(worker_count):
    state = Parameter(para.mu.clone(), para.sigma.clone(), para.gamma.clone(),
                      para.delta.clone(), para.theta.clone())
    server_n = GlobalComputation(knots, Matern_1_5_kernel, step_size=1., type_LR="P")
    server_n.set_global_para_ind_quantities({"J": worker_count})
    with open(out / f"N_WORKER_{worker_count}_P_CHECKPOINTS.csv", "w", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(["round", "stage", "gamma0", "mu0", "mu1", "sigma00", "sigma01", "sigma10", "sigma11", "delta", "alpha", "range", "accepted_step", "halving_count"])
        for round_id in range(2):
            local_mu_sigma = []
            for local_data in n_worker_data[:worker_count]:
                local = LocalComputation(local_data, Matern_1_5_kernel, knots); local.type_LR = "P"
                local_mu_sigma.append(local.compute_local_for_mu_sigma(state))
            summary = {"mu": sum((x["mu"] for x in local_mu_sigma)) / worker_count,
                       "sigma": sum((x["sigma"] for x in local_mu_sigma)) / worker_count}
            state = server_n.update_mu_Sigma(state, summary)
            def record(stage, accepted_step=1., halving_count=0):
                writer.writerow([round_id, stage, state.gamma.item(), state.mu[0].item(), state.mu[1].item(),
                                 state.sigma[0,0].item(), state.sigma[0,1].item(), state.sigma[1,0].item(), state.sigma[1,1].item(),
                                 state.delta.item(), state.theta[0].item(), state.theta[1].item(), accepted_step, halving_count])
            record("mu_sigma")
            local_gamma = []
            for local_data in n_worker_data[:worker_count]:
                local = LocalComputation(local_data, Matern_1_5_kernel, knots); local.type_LR = "P"
                local_gamma.append(local.compute_local_for_gamma(state))
            gamma_summary = {"gamma": sum((x["gamma"] for x in local_gamma)) / worker_count,
                             "XX": sum((x["XX"] for x in local_gamma)) / worker_count}
            state = server_n.update_gamma(state, gamma_summary)
            record("gamma")
            local_theta = []
            for local_data in n_worker_data[:worker_count]:
                local = LocalComputation(local_data, Matern_1_5_kernel, knots); local.type_LR = "P"
                local_theta.append(local.compute_local_for_theta_delta(state))
            theta_summary = {"grad": sum((x["grad"] for x in local_theta)) / worker_count,
                             "hessian": sum((x["hessian"] for x in local_theta)) / worker_count}
            # Diagnostics mirror the accepted-step branch only; state is still
            # returned by the authoritative Python update method.
            correction = server_n.Grad_Hessian_f(state)
            correction_grad = torch.cat((torch.zeros((1,1), dtype=torch.float64), correction["grad"].reshape(-1,1)), dim=0)
            correction_hessian = torch.zeros((3,3), dtype=torch.float64); correction_hessian[1:,1:] = correction["hessian"]
            gradient = theta_summary["grad"].unsqueeze(1) * worker_count + correction_grad
            hessian = theta_summary["hessian"] * worker_count + correction_hessian
            eigvals, eigvecs = torch.linalg.eigh(hessian)
            modified = eigvecs @ torch.diag(torch.maximum(eigvals.abs(), torch.tensor(.01, dtype=torch.float64))) @ eigvecs.T
            direction = torch.linalg.inv(modified) @ gradient
            accepted_step, halving_count = server_n.step_size, 0
            candidate = torch.cat((state.delta.reshape(1), state.theta.reshape(-1))) - accepted_step * direction.reshape(-1)
            while (candidate <= 0).any():
                accepted_step /= 2; halving_count += 1
                candidate = torch.cat((state.delta.reshape(1), state.theta.reshape(-1))) - accepted_step * direction.reshape(-1)
            state = server_n.update_delta_theta(state, theta_summary)
            record("delta_theta", accepted_step, halving_count)

